--- Player-facing text owned by the inventory module.
-- @author dop42
--
-- Every key here is a refusal code, a confirmation, a word the page draws or an
-- item's name. It reaches `locale()` through a variable, never as a literal, so a
-- rename breaks nothing at load and everything at the moment a player is refused.
--
-- Both halves need them: the server renders a toast and a command answer, and the
-- client renders the code `OPX.Refuse` carries. The page is handed the whole
-- catalogue once at boot, because it cannot call back for a string per render.
--
-- Keys resolved at run time, each composed from a literal prefix so that no key
-- here is orphaned and none is unreachable:
--   inventory.item.<name>              and .description  (Catalog.Label/Description)
--   inventory.error.<code>             falling back to inventory.error.failed
--   inventory.command.error.<code>     falling back to inventory.command.error.failed
--   inventory.tab.<KEY>                one per configured tab
--   inventory.ui.<key>                 the words the page draws

